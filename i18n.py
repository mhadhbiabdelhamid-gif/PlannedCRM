def current_lang():
    """Per-user preference wins, then the session, then English."""
    user = g.get("user")
    if user is not None and "lang" in user.keys() and user["lang"] in LANGS:
        return user["lang"]
    lang = session.get("lang", "en")
    return lang if lang in LANGS else "en"


def t(text):
    if current_lang() == "ar":
        return AR.get(text, text)
    return text


